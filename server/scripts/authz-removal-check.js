'use strict';
// "We will take one authorisation check out of your code and run your tests."
//
// This script does exactly that, for EVERY check, one at a time:
//   1. finds each line marked   <code>  // AUTHZ:<name> -> <code without the check>
//   2. copies the server into a temporary folder,
//   3. replaces that one line with its "check removed" version,
//   4. runs the full test suite against the copy,
//   5. reports CAUGHT (some test failed, good) or MISSED (all passed, bad).
// Exits with code 1 if any removal was missed.
//
// Usage:  npm run test:authz-removal              (all checks)
//         npm run test:authz-removal -- canRead   (only checks whose name contains "canRead")
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const SERVER = path.join(ROOT, 'server');
const MARK = /^(\s*)(.*?)\s*\/\/ AUTHZ:([\w-]+) -> (.+)$/;
const filter = process.argv[2] || '';

function listFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return listFiles(p);
    return p.endsWith('.js') ? [p] : [];
  });
}

function findMarkers() {
  const markers = [];
  for (const file of listFiles(path.join(SERVER, 'src'))) {
    fs.readFileSync(file, 'utf8').split('\n').forEach((line, i) => {
      const m = line.match(MARK);
      if (m) markers.push({ file: path.relative(ROOT, file), line: i, name: m[3], indent: m[1], original: m[2], removed: m[4].trim() });
    });
  }
  return markers.filter((m) => m.name.includes(filter));
}

function runTests(serverDir) {
  const testDir = path.join(serverDir, 'test');
  const files = fs.readdirSync(testDir).filter((f) => f.endsWith('.test.js')).map((f) => path.join(testDir, f));
  const r = spawnSync(process.execPath, ['--test', '--test-concurrency=1', ...files], {
    cwd: path.dirname(serverDir),
    env: { ...process.env, NODE_ENV: 'test' },
    encoding: 'utf8',
    timeout: 10 * 60 * 1000,
  });
  const out = `${r.stdout || ''}${r.stderr || ''}`;
  const fail = Number((out.match(/^# fail (\d+)/m) || [])[1] || 0);
  const pass = Number((out.match(/^# pass (\d+)/m) || [])[1] || 0);
  const failedNames = [...out.matchAll(/^\s*not ok \d+ - (.+)$/gm)].map((x) => x[1]).filter((n) => !/^T\d+ /.test(n) || true);
  return { code: r.status, pass, fail, failedNames };
}

function makeCopy() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tv-authz-'));
  fs.cpSync(SERVER, path.join(tmp, 'server'), { recursive: true });
  fs.symlinkSync(path.join(ROOT, 'node_modules'), path.join(tmp, 'node_modules'), 'dir');
  return tmp;
}

function main() {
  const markers = findMarkers();
  if (markers.length === 0) {
    console.log('No AUTHZ markers found.');
    process.exit(1);
  }
  console.log(`Baseline: running the test suite on the unmodified code...`);
  const base = runTests(SERVER);
  if (base.code !== 0) {
    console.error(`Baseline failed (${base.fail} failing). Fix the tests first.`);
    process.exit(1);
  }
  console.log(`Baseline OK: ${base.pass} tests pass.\n`);
  console.log(`Removing ${markers.length} checks, one at a time:\n`);

  const results = [];
  for (const m of markers) {
    const tmp = makeCopy();
    try {
      const target = path.join(tmp, m.file);
      const lines = fs.readFileSync(target, 'utf8').split('\n');
      lines[m.line] = `${m.indent}${m.removed}`;
      fs.writeFileSync(target, lines.join('\n'));
      const r = runTests(path.join(tmp, 'server'));
      const caught = r.code !== 0 && r.fail > 0;
      results.push({ ...m, caught, fail: r.fail, example: r.failedNames.find((n) => !/^T\d+ |^Session|^Admin/.test(n)) || r.failedNames[0] });
      console.log(`${caught ? 'CAUGHT' : 'MISSED'}  ${m.name.padEnd(28)} ${m.file}:${m.line + 1}  (${r.fail} failing tests)`);
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  }

  const missed = results.filter((r) => !r.caught);
  console.log(`\n${results.length - missed.length}/${results.length} removed checks were caught by the tests.`);

  const report = [
    '# Authorisation-check removal report',
    '',
    `Generated by \`npm run test:authz-removal\` on ${new Date().toISOString()}.`,
    '',
    `Baseline: ${base.pass} tests passing. Each row below removes ONE check and re-runs all tests.`,
    '',
    '| Check | Where | Result | Failing tests | Example test that caught it |',
    '| --- | --- | --- | --- | --- |',
    ...results.map((r) => `| \`${r.name}\` | \`${r.file}:${r.line + 1}\` | ${r.caught ? 'Caught' : '**MISSED**'} | ${r.fail} | ${r.example ? r.example.replace(/\|/g, '/') : ''} |`),
    '',
  ].join('\n');
  if (!filter) fs.writeFileSync(path.join(ROOT, 'docs', 'authz-removal-report.md'), report);

  process.exit(missed.length ? 1 : 0);
}

main();
